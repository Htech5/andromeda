"""Turn the M31 render into a binary-digit grid for the hero.

Each cell is ' ' (empty) or '0'-'9' = brightness bucket. The page picks 1 or 0
per cell at runtime, weighted by that bucket, so the silhouette shimmers.
"""
import numpy as np
from PIL import Image

COLS, ROWS = 96, 50
CHAR_RATIO = 0.5  # monospace cells are about twice as tall as wide

im = Image.open("robot-quarter.png")
a = np.asarray(im).astype(np.float32)
alpha, lum = a[..., 3] / 255, a[..., 0] / 255

ys, xs = np.nonzero(alpha > 0.35)
im = im.crop((xs.min(), ys.min(), xs.max() + 1, ys.max() + 1))
a = np.asarray(im).astype(np.float32)
alpha, lum = a[..., 3] / 255, a[..., 0] / 255

h, w = alpha.shape
cell_w, cell_h = w / COLS, h / ROWS
rows = []
for r in range(ROWS):
    line = []
    for c in range(COLS):
        y0, y1 = int(r * cell_h), max(int((r + 1) * cell_h), int(r * cell_h) + 1)
        x0, x1 = int(c * cell_w), max(int((c + 1) * cell_w), int(c * cell_w) + 1)
        cov = alpha[y0:y1, x0:x1].mean()
        if cov < 0.34:
            line.append(" ")
            continue
        v = lum[y0:y1, x0:x1][alpha[y0:y1, x0:x1] > 0.3]
        b = float(v.mean()) if v.size else 0.5
        line.append(str(min(9, max(0, int(round(b * 9))))))
    rows.append("".join(line).rstrip())

print("\n".join(r.replace("0", ".").replace("9", "#") for r in rows))
print("---")
ts = (
    "/** Generated by scripts/make_ascii.py from the M31 CAD render.\n"
    " *  ' ' = empty, '0'-'9' = brightness bucket for the binary shimmer. */\n"
    "export const asciiRobot = [\n"
    + "".join(f"  {r!r},\n".replace("'", '"') for r in rows)
    + "] as const;\n"
)
open("asciiRobot.ts", "w", encoding="utf-8", newline="\n").write(ts)
print("cols", COLS, "rows", ROWS, "bytes", len(ts))
